//! Slide XML emission: turns a [`SlideSpec`] into `p:sld` markup plus the
//! slide's relationships (images, hyperlinks). Geometry comes from a
//! [`Skin`] — the built-in skin or one parsed from a template's layouts.
//!
//! Placeholder-bound text deliberately omits font sizes and colors so the
//! master/layout styles win (that is what makes template decks keep their
//! look); plain text boxes carry explicit formatting.

use docgen_core::assets::{AssetFormat, AssetMap};
use docgen_core::model::Inline;

use super::spec::{Bullet, Elem, SlideKind, SlideSpec};
use super::Error;
use crate::docx::package::png_dimensions;
use crate::docx::xml::Xml;

pub(crate) type Geom = (i64, i64, i64, i64);

/// Emission "skin": placeholder boxes and layout targets. The default skin
/// matches the parts generated by `parts.rs`; template filling builds one
/// from the template's own layouts so slides inherit its look.
pub(crate) struct Skin {
    /// Relationship target of the layout used by title slides.
    pub title_layout: String,
    /// Relationship target of the layout used by content slides.
    pub content_layout: String,
    pub title_geom: Geom,
    pub ctr_title_geom: Geom,
    pub subtitle_geom: Geom,
    pub body_geom: Geom,
    /// Placeholder idx of the layout's body placeholder; `None` falls back
    /// to a plain text box with explicit bullet formatting.
    pub body_idx: Option<u32>,
    /// Theme minor font, stamped on non-code runs. LibreOffice leaks an
    /// explicit `a:latin` to following runs that lack one, so every run
    /// carries a font explicitly.
    pub body_font: String,
}

impl Clone for Skin {
    fn clone(&self) -> Self {
        Self {
            title_layout: self.title_layout.clone(),
            content_layout: self.content_layout.clone(),
            title_geom: self.title_geom,
            ctr_title_geom: self.ctr_title_geom,
            subtitle_geom: self.subtitle_geom,
            body_geom: self.body_geom,
            body_idx: self.body_idx,
            body_font: self.body_font.clone(),
        }
    }
}

impl Default for Skin {
    fn default() -> Self {
        use super::parts::*;
        Self {
            title_layout: "../slideLayouts/slideLayout1.xml".to_string(),
            content_layout: "../slideLayouts/slideLayout2.xml".to_string(),
            title_geom: TITLE_GEOM,
            ctr_title_geom: CTR_TITLE_GEOM,
            subtitle_geom: SUBTITLE_GEOM,
            body_geom: BODY_GEOM,
            body_idx: Some(1),
            body_font: "Calibri".to_string(),
        }
    }
}

/// Allocates `ppt/media/imageN.png` names across slides.
pub(crate) struct MediaAlloc {
    next: usize,
    pub files: Vec<(String, Vec<u8>)>,
}

impl Default for MediaAlloc {
    fn default() -> Self {
        Self::new(1)
    }
}

impl MediaAlloc {
    pub(crate) fn new(first_index: usize) -> Self {
        Self {
            next: first_index,
            files: Vec::new(),
        }
    }

    fn add_png(&mut self, bytes: &[u8]) -> String {
        let name = format!("image{}.png", self.next);
        self.next += 1;
        self.files.push((name.clone(), bytes.to_vec()));
        name
    }
}

/// A relationship on a slide (rIds start at 2; rId1 is the layout).
pub(crate) struct Rel {
    pub target: String,
    pub external: bool,
}

/// `ppt/slides/_rels/slideN.xml.rels`.
pub(crate) fn slide_rels_xml(layout_target: &str, rels: &[Rel]) -> String {
    let esc = crate::docx::xml::esc_attr;
    let mut out = String::from(
        r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slideLayout" Target=""#,
    );
    out.push_str(&esc(layout_target));
    out.push_str("\"/>\n");
    for (i, rel) in rels.iter().enumerate() {
        let kind = if rel.external { "hyperlink" } else { "image" };
        let mode = if rel.external { " TargetMode=\"External\"" } else { "" };
        out.push_str(&format!(
            "  <Relationship Id=\"rId{rid}\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/{kind}\" Target=\"{target}\"{mode}/>\n",
            rid = i + 2,
            target = esc(&rel.target)
        ));
    }
    out.push_str("</Relationships>\n");
    out
}

pub(crate) struct SlideOut {
    pub xml: Vec<u8>,
    pub rels: Vec<Rel>,
    pub layout: String,
}

/// One flattened run of uniformly-styled text, keeping link targets.
#[derive(Clone)]
struct PRun {
    bold: bool,
    italic: bool,
    strike: bool,
    code: bool,
    link: Option<String>,
    text: String,
}

impl PRun {
    fn text(text: &str) -> Self {
        Self {
            bold: false,
            italic: false,
            strike: false,
            code: false,
            link: None,
            text: text.to_string(),
        }
    }
}

fn flatten(inlines: &[Inline]) -> Vec<PRun> {
    let mut out: Vec<PRun> = Vec::new();
    walk(inlines, false, false, false, false, None, &mut out);
    out
}

fn walk(
    inlines: &[Inline],
    bold: bool,
    italic: bool,
    strike: bool,
    code: bool,
    link: Option<&str>,
    out: &mut Vec<PRun>,
) {
    for inline in inlines {
        match inline {
            Inline::Text(t) => push_run(out, bold, italic, strike, code, link, t),
            Inline::Code(t) => push_run(out, bold, italic, strike, true, link, t),
            Inline::SoftBreak | Inline::HardBreak => {
                push_run(out, bold, italic, strike, code, link, " ")
            }
            Inline::Strong(inner) => walk(inner, true, italic, strike, code, link, out),
            Inline::Emphasis(inner) => walk(inner, bold, true, strike, code, link, out),
            Inline::Strikethrough(inner) => walk(inner, bold, italic, true, code, link, out),
            Inline::Link { url, text } => walk(text, bold, italic, strike, code, Some(url), out),
            Inline::Image { alt, .. } => walk(alt, bold, italic, strike, code, link, out),
        }
    }
}

fn push_run(
    out: &mut Vec<PRun>,
    bold: bool,
    italic: bool,
    strike: bool,
    code: bool,
    link: Option<&str>,
    text: &str,
) {
    if text.is_empty() {
        return;
    }
    let same = out.last().is_some_and(|r| {
        r.bold == bold
            && r.italic == italic
            && r.strike == strike
            && r.code == code
            && r.link.as_deref() == link
    });
    if same {
        out.last_mut().unwrap().text.push_str(text);
    } else {
        out.push(PRun {
            bold,
            italic,
            strike,
            code,
            link: link.map(str::to_string),
            text: text.to_string(),
        });
    }
}

fn tag_color(tag: &str) -> &'static str {
    match tag {
        "new" => "1E7B34",
        "updated" => "B25F00",
        "moved" => "1F5FBF",
        "removed" => "A02020",
        _ => "595959",
    }
}

pub(crate) fn emit_slide(
    spec: &SlideSpec,
    skin: &Skin,
    assets: &AssetMap,
    media: &mut MediaAlloc,
) -> Result<SlideOut, Error> {
    let mut xml = Xml::new();
    let mut rels: Vec<Rel> = Vec::new();
    {
        let mut ctx = Ctx {
            xml: &mut xml,
            rels: &mut rels,
            next_id: 2,
            font: &skin.body_font,
        };

        ctx.xml.start(
        "p:sld",
        &[
            ("xmlns:a", "http://schemas.openxmlformats.org/drawingml/2006/main"),
            ("xmlns:r", "http://schemas.openxmlformats.org/officeDocument/2006/relationships"),
            ("xmlns:p", "http://schemas.openxmlformats.org/presentationml/2006/main"),
        ],
    );
    ctx.xml.start("p:cSld", &[]);
    ctx.xml.start("p:spTree", &[]);
    ctx.xml.start("p:nvGrpSpPr", &[]);
    ctx.xml.empty("p:cNvPr", &[("id", "1"), ("name", "")]);
    ctx.xml.empty("p:cNvGrpSpPr", &[]);
    ctx.xml.empty("p:nvPr", &[]);
    ctx.xml.end("p:nvGrpSpPr");
    ctx.xml.start("p:grpSpPr", &[]);
    ctx.xml.start("a:xfrm", &[]);
    ctx.xml.empty("a:off", &[("x", "0"), ("y", "0")]);
    ctx.xml.empty("a:ext", &[("cx", "0"), ("cy", "0")]);
    ctx.xml.empty("a:chOff", &[("x", "0"), ("y", "0")]);
    ctx.xml.empty("a:chExt", &[("cx", "0"), ("cy", "0")]);
    ctx.xml.end("a:xfrm");
    ctx.xml.end("p:grpSpPr");

    match spec.kind {
        SlideKind::Title => {
            let text = spec.title.clone().unwrap_or_default();
            shape_ph(&mut ctx, "ctrTitle", None, skin.ctr_title_geom, &text, true);
            if let Some(sub) = &spec.subtitle {
                shape_ph(&mut ctx, "subTitle", Some(1), skin.subtitle_geom, sub, true);
            }
            if let Some(bye) = &spec.byline {
                textbox(
                    &mut ctx,
                    super::parts::META_GEOM,
                    &[PRun::text(bye)],
                    Some(1300),
                    "737373",
                    false,
                    false,
                );
            }
        }
        SlideKind::Content => {
            if let Some(title) = &spec.title {
                shape_ph(&mut ctx, "title", None, skin.title_geom, title, false);
            }
            if let Some(tag) = spec.tag {
                tag_chip(&mut ctx, tag);
            }
            let has_lead = spec
                .elems
                .iter()
                .any(|e| matches!(e, Elem::Lead(_) | Elem::Quote(_)));
            let mut bullet_area = skin.body_geom;
            if has_lead {
                bullet_area.1 += 1_000_000;
                bullet_area.3 = bullet_area.3.saturating_sub(1_000_000);
            }
            for elem in &spec.elems {
                match elem {
                    Elem::Lead(inline) => textbox(
                        &mut ctx,
                        (skin.body_geom.0, skin.body_geom.1, skin.body_geom.2, 914_400),
                        &flatten(inline),
                        Some(1700),
                        "404040",
                        false,
                        false,
                    ),
                    Elem::Quote(inline) => textbox(
                        &mut ctx,
                        (skin.body_geom.0, skin.body_geom.1, skin.body_geom.2, 914_400),
                        &flatten(inline),
                        Some(1700),
                        "595959",
                        true,
                        false,
                    ),
                    Elem::Bullets(bullets) => bullets_shape(&mut ctx, skin, bullet_area, bullets),
                    Elem::Table(rows) => table(&mut ctx, skin.body_geom, rows),
                    Elem::Picture { block_id, alt } => {
                        picture(&mut ctx, skin.body_geom, block_id, alt, assets, media)?
                    }
                    Elem::Code { language, code } => {
                        code_box(&mut ctx, skin.body_geom, language.as_deref(), code)
                    }
                }
            }
        }
    }

        ctx.xml.end("p:spTree");
        ctx.xml.end("p:cSld");
        ctx.xml.start("p:clrMapOvr", &[]);
        ctx.xml.empty("a:masterClrMapping", &[]);
        ctx.xml.end("p:clrMapOvr");
        ctx.xml.end("p:sld");
    }

    Ok(SlideOut {
        xml: xml.finish(),
        rels,
        layout: match spec.kind {
            SlideKind::Title => skin.title_layout.clone(),
            SlideKind::Content => skin.content_layout.clone(),
        },
    })
}

/// Mutable borrow bundle so element writers stay signature-light.
struct Ctx<'a> {
    xml: &'a mut Xml,
    rels: &'a mut Vec<Rel>,
    next_id: usize,
    /// Deck-wide minor font for explicit `a:latin` on plain runs.
    font: &'a str,
}

impl Ctx<'_> {
    fn id(&mut self) -> usize {
        let id = self.next_id;
        self.next_id += 1;
        id
    }

    fn image_rid(&mut self, file: &str) -> usize {
        self.rels.push(Rel {
            target: format!("../media/{file}"),
            external: false,
        });
        self.rels.len() + 1
    }

    fn link_rid(&mut self, url: &str) -> usize {
        if let Some(i) = self.rels.iter().position(|r| r.target == url && r.external) {
            return i + 2;
        }
        self.rels.push(Rel {
            target: url.to_string(),
            external: true,
        });
        self.rels.len() + 1
    }
}

fn xfrm_attrs(xml: &mut Xml, (x, y, cx, cy): Geom) {
    xml.start("a:xfrm", &[]);
    xml.empty("a:off", &[("x", &x.to_string()), ("y", &y.to_string())]);
    xml.empty("a:ext", &[("cx", &cx.to_string()), ("cy", &cy.to_string())]);
    xml.end("a:xfrm");
}

fn rect_geom(xml: &mut Xml) {
    xml.start("a:prstGeom", &[("prst", "rect")]);
    xml.start("a:avLst", &[]);
    xml.end("a:avLst");
    xml.end("a:prstGeom");
}

/// Placeholder shape with explicit geometry (deterministic in every
/// renderer) but no run styling — the master/layout styles apply.
fn shape_ph(ctx: &mut Ctx, ph: &str, idx: Option<u32>, geom: Geom, text: &str, centered: bool) {
    let id = ctx.id();
    ctx.xml.start("p:sp", &[]);
    ctx.xml.start("p:nvSpPr", &[]);
    ctx.xml.empty(
        "p:cNvPr",
        &[("id", &id.to_string()), ("name", &format!("Placeholder {id}"))],
    );
    // Placeholders are not text boxes: txBox="1" here is contradictory and
    // PowerPoint flags the deck for repair.
    ctx.xml.start("p:cNvSpPr", &[]);
    ctx.xml.empty("a:spLocks", &[("noGrp", "1")]);
    ctx.xml.end("p:cNvSpPr");
    ctx.xml.start("p:nvPr", &[]);
    if let Some(idx) = idx {
        ctx.xml.empty("p:ph", &[("type", ph), ("idx", &idx.to_string())]);
    } else {
        ctx.xml.empty("p:ph", &[("type", ph)]);
    }
    ctx.xml.end("p:nvPr");
    ctx.xml.end("p:nvSpPr");
    ctx.xml.start("p:spPr", &[]);
    xfrm_attrs(ctx.xml, geom);
    rect_geom(ctx.xml);
    ctx.xml.end("p:spPr");
    ctx.xml.start("p:txBody", &[]);
    if centered {
        ctx.xml.empty("a:bodyPr", &[("anchor", "ctr")]);
    } else {
        ctx.xml.empty("a:bodyPr", &[("wrap", "square")]);
    }
    ctx.xml.start("a:lstStyle", &[]);
    ctx.xml.end("a:lstStyle");
    if text.is_empty() {
        ctx.xml.start("a:p", &[]);
        ctx.xml.empty("a:endParaRPr", &[("lang", "en-US")]);
        ctx.xml.end("a:p");
    } else {
        write_para(
            ctx,
            &[],
            None,
            &[PRun::text(text)],
            ParaOpts::default(),
        );
    }
    ctx.xml.end("p:txBody");
    ctx.xml.end("p:sp");
}

/// Plain text box with explicit formatting.
fn textbox(
    ctx: &mut Ctx,
    geom: Geom,
    pruns: &[PRun],
    size: Option<usize>,
    color: &'static str,
    italic: bool,
    centered: bool,
) {
    let id = ctx.id();
    ctx.xml.start("p:sp", &[]);
    ctx.xml.start("p:nvSpPr", &[]);
    ctx.xml.empty(
        "p:cNvPr",
        &[("id", &id.to_string()), ("name", &format!("TextBox {id}"))],
    );
    ctx.xml.empty("p:cNvSpPr", &[("txBox", "1")]);
    ctx.xml.empty("p:nvPr", &[]);
    ctx.xml.end("p:nvSpPr");
    ctx.xml.start("p:spPr", &[]);
    xfrm_attrs(ctx.xml, geom);
    rect_geom(ctx.xml);
    ctx.xml.end("p:spPr");
    ctx.xml.start("p:txBody", &[]);
    let anchor = if centered { "ctr" } else { "t" };
    ctx.xml.empty("a:bodyPr", &[("wrap", "square"), ("anchor", anchor)]);
    ctx.xml.start("a:lstStyle", &[]);
    ctx.xml.end("a:lstStyle");
    if pruns.is_empty() {
        ctx.xml.start("a:p", &[]);
        ctx.xml.empty("a:endParaRPr", &[("lang", "en-US")]);
        ctx.xml.end("a:p");
    } else {
        let mut styled: Vec<PRun> = pruns.to_vec();
        if italic {
            for r in &mut styled {
                r.italic = true;
            }
        }
        let font = ctx.font.to_string();
        write_para(
            ctx,
            &[("marL".into(), "0".into()), ("indent".into(), "0".into())],
            Some(PprChildren::NoBullet),
            &styled,
            ParaOpts {
                size,
                color: Some(color),
                font: Some(font),
                ..ParaOpts::default()
            },
        );
    }
    ctx.xml.end("p:txBody");
    ctx.xml.end("p:sp");
}

/// Revision chip in the top-right corner.
fn tag_chip(ctx: &mut Ctx, tag: &str) {
    let id = ctx.id();
    let id_s = id.to_string();
    ctx.xml.start("p:sp", &[]);
    ctx.xml.start("p:nvSpPr", &[]);
    ctx.xml
        .empty("p:cNvPr", &[("id", id_s.as_str()), ("name", "Revision tag")]);
    ctx.xml.empty("p:cNvSpPr", &[("txBox", "1")]);
    ctx.xml.empty("p:nvPr", &[]);
    ctx.xml.end("p:nvSpPr");
    ctx.xml.start("p:spPr", &[]);
    xfrm_attrs(ctx.xml, super::parts::TAG_GEOM);
    rect_geom(ctx.xml);
    ctx.xml.end("p:spPr");
    ctx.xml.start("p:txBody", &[]);
    ctx.xml.empty("a:bodyPr", &[("wrap", "square"), ("anchor", "ctr")]);
    ctx.xml.start("a:lstStyle", &[]);
    ctx.xml.end("a:lstStyle");
    write_para(
        ctx,
        &[("algn".into(), "r".into())],
        Some(PprChildren::NoBullet),
        &[PRun {
            bold: true,
            italic: false,
            strike: false,
            code: false,
            link: None,
            text: tag.to_ascii_uppercase(),
        }],
        ParaOpts {
            size: Some(1100),
            color: Some(tag_color(tag)),
            ..ParaOpts::default()
        },
    );
    ctx.xml.end("p:txBody");
    ctx.xml.end("p:sp");
}

/// Bullet list: a body placeholder when the skin has one (so template
/// bullet styles apply), else a text box with explicit bullet formatting.
fn bullets_shape(ctx: &mut Ctx, skin: &Skin, geom: Geom, bullets: &[Bullet]) {
    let id = ctx.id();
    let explicit = skin.body_idx.is_none();
    ctx.xml.start("p:sp", &[]);
    ctx.xml.start("p:nvSpPr", &[]);
    ctx.xml.empty(
        "p:cNvPr",
        &[("id", &id.to_string()), ("name", &format!("Content {id}"))],
    );
    if skin.body_idx.is_some() {
        // Body placeholder, not a text box (txBox would trip repair).
        ctx.xml.start("p:cNvSpPr", &[]);
        ctx.xml.empty("a:spLocks", &[("noGrp", "1")]);
        ctx.xml.end("p:cNvSpPr");
    } else {
        ctx.xml.empty("p:cNvSpPr", &[("txBox", "1")]);
    }
    ctx.xml.start("p:nvPr", &[]);
    if let Some(idx) = skin.body_idx {
        ctx.xml.empty("p:ph", &[("type", "body"), ("idx", &idx.to_string())]);
    }
    ctx.xml.end("p:nvPr");
    ctx.xml.end("p:nvSpPr");
    ctx.xml.start("p:spPr", &[]);
    xfrm_attrs(ctx.xml, geom);
    rect_geom(ctx.xml);
    ctx.xml.end("p:spPr");
    ctx.xml.start("p:txBody", &[]);
    ctx.xml.empty("a:bodyPr", &[]);
    ctx.xml.start("a:lstStyle", &[]);
    ctx.xml.end("a:lstStyle");
    for b in bullets {
        let runs = flatten(&b.runs);
        let ppr = bullet_ppr(b, explicit);
        let children = if b.ordered {
            Some(PprChildren::AutoNum(b.number))
        } else if explicit {
            Some(PprChildren::Bullet(b.level))
        } else {
            // Placeholder body: the master supplies the bullet character.
            None
        };
        let font = ctx.font.to_string();
        write_para(
            ctx,
            &ppr,
            children,
            &runs,
            ParaOpts {
                size: if explicit { Some(1800) } else { None },
                font: Some(font),
                ..ParaOpts::default()
            },
        );
    }
    if bullets.is_empty() {
        ctx.xml.start("a:p", &[]);
        ctx.xml.empty("a:endParaRPr", &[("lang", "en-US")]);
        ctx.xml.end("a:p");
    }
    ctx.xml.end("p:txBody");
    ctx.xml.end("p:sp");
}

/// Paragraph properties for a bullet.
fn bullet_ppr(b: &Bullet, explicit: bool) -> Vec<(String, String)> {
    if explicit {
        let (mar_l, indent) = match b.level {
            0 => (342_900, 342_900),
            1 => (742_950, 342_900),
            _ => (1_143_000, 228_600),
        };
        vec![
            ("lvl".into(), b.level.to_string()),
            ("marL".into(), mar_l.to_string()),
            ("indent".into(), format!("-{indent}")),
        ]
    } else {
        vec![("lvl".into(), b.level.to_string())]
    }
}

/// Children written inside `a:pPr` for special paragraphs.
enum PprChildren {
    NoBullet,
    Bullet(u8),
    AutoNum(u64),
}

#[derive(Default)]
struct ParaOpts {
    size: Option<usize>,
    color: Option<&'static str>,
    bold_all: bool,
    /// Explicit minor font for non-code runs (leak-proofing).
    font: Option<String>,
}

/// Writes one `a:p` with optional `a:pPr` attributes and children.
fn write_para(
    ctx: &mut Ctx,
    ppr: &[(String, String)],
    children: Option<PprChildren>,
    pruns: &[PRun],
    opts: ParaOpts,
) {
    ctx.xml.start("a:p", &[]);
    let borrowed: Vec<(&str, &str)> = ppr.iter().map(|(k, v)| (k.as_str(), v.as_str())).collect();
    ctx.xml.start("a:pPr", &borrowed);
    match children {
        Some(PprChildren::NoBullet) => {
            ctx.xml.start("a:buFont", &[("typeface", "Arial"), ("charset", "0")]);
            ctx.xml.end("a:buFont");
            ctx.xml.empty("a:buNone", &[]);
        }
        Some(PprChildren::Bullet(level)) => {
            ctx.xml.start("a:buFont", &[("typeface", "Arial"), ("charset", "0")]);
            ctx.xml.end("a:buFont");
            ctx.xml.empty("a:buChar", &[("char", bullet_char(level))]);
        }
        Some(PprChildren::AutoNum(start)) => {
            ctx.xml
                .empty("a:buAutoNum", &[("type", "arabicPeriod"), ("startAt", &start.to_string())]);
        }
        None => {}
    }
    ctx.xml.end("a:pPr");
    write_runs(ctx, pruns, &opts);
    ctx.xml.end("a:p");
}

fn bullet_char(level: u8) -> &'static str {
    match level {
        0 => "•",
        1 => "–",
        _ => "•",
    }
}

fn write_runs(ctx: &mut Ctx, pruns: &[PRun], opts: &ParaOpts) {
    // LibreOffice leaks an explicit a:latin into later runs of the same
    // paragraph that lack one, so every run gets a font: Consolas for code
    // spans, the deck's minor font otherwise. Runs bound to placeholder
    // inheritance (titles) only stamp a font when the paragraph mixes in a
    // code span, which is what triggers the leak.
    let fallback_font = opts
        .font
        .clone()
        .or_else(|| pruns.iter().any(|r| r.code).then(|| ctx.font.to_string()));
    for r in pruns {
        ctx.xml.start("a:r", &[]);
        // bold/italic/strike are ATTRIBUTES of a:rPr; solidFill/latin/
        // hlinkClick are children in that schema order.
        let mut attrs: Vec<(&str, String)> = vec![
            ("lang", "en-US".to_string()),
            ("dirty", "0".to_string()),
        ];
        if let Some(sz) = opts.size {
            attrs.push(("sz", sz.to_string()));
        }
        if opts.bold_all || r.bold {
            attrs.push(("b", "1".to_string()));
        }
        if r.italic {
            attrs.push(("i", "1".to_string()));
        }
        if r.strike {
            attrs.push(("strike", "sngStrike".to_string()));
        }
        let borrowed: Vec<(&str, &str)> = attrs.iter().map(|(k, v)| (*k, v.as_str())).collect();
        ctx.xml.start("a:rPr", &borrowed);
        if let Some(c) = opts.color {
            ctx.xml.start("a:solidFill", &[]);
            ctx.xml.empty("a:srgbClr", &[("val", c)]);
            ctx.xml.end("a:solidFill");
        }
        if r.code {
            ctx.xml.empty("a:latin", &[("typeface", "Consolas")]);
        } else if let Some(f) = &fallback_font {
            ctx.xml.empty("a:latin", &[("typeface", f)]);
        }
        if let Some(url) = &r.link {
            let rid = ctx.link_rid(url);
            ctx.xml
                .empty("a:hlinkClick", &[("r:id", &format!("rId{rid}"))]);
        }
        ctx.xml.end("a:rPr");
        ctx.xml.start("a:t", &[]);
        ctx.xml.text(&r.text);
        ctx.xml.end("a:t");
        ctx.xml.end("a:r");
    }
}

/// Markdown table → DrawingML table in a graphicFrame.
fn table(ctx: &mut Ctx, geom: Geom, rows: &[docgen_core::model::TableRow]) {
    use docgen_core::model::TableRow;
    let cols = rows
        .first()
        .map(|r: &TableRow| r.cells.len())
        .unwrap_or(0)
        .max(1);

    // Column widths proportional to the longest cell text, clamped so a
    // long cell cannot starve the others.
    let mut weights = vec![4usize; cols];
    for row in rows {
        for (c, cell) in row.cells.iter().enumerate().take(cols) {
            let len = Inline::plain_text(cell).chars().count();
            weights[c] = weights[c].max(len.min(50));
        }
    }
    let total_weight: usize = weights.iter().sum();
    let col_w: Vec<i64> = weights
        .iter()
        .map(|w| (geom.2 as i128 * *w as i128 / total_weight.max(1) as i128) as i64)
        .collect();

    let id = ctx.id();
    ctx.xml.start("p:graphicFrame", &[]);
    ctx.xml.start("p:nvGraphicFramePr", &[]);
    ctx.xml.empty(
        "p:cNvPr",
        &[("id", &id.to_string()), ("name", &format!("Table {id}"))],
    );
    ctx.xml.empty("p:cNvGraphicFramePr", &[]);
    ctx.xml.empty("p:nvPr", &[]);
    ctx.xml.end("p:nvGraphicFramePr");
    // GraphicFrames carry the presentation-namespace transform (p:xfrm),
    // unlike shapes (a:xfrm) — PowerPoint flags the deck for repair if
    // the wrong one is used.
    ctx.xml.start("p:xfrm", &[]);
    ctx.xml
        .empty("a:off", &[("x", &geom.0.to_string()), ("y", &geom.1.to_string())]);
    ctx.xml
        .empty("a:ext", &[("cx", &geom.2.to_string()), ("cy", &geom.3.to_string())]);
    ctx.xml.end("p:xfrm");
    ctx.xml.start("a:graphic", &[]);
    ctx.xml.start(
        "a:graphicData",
        &[("uri", "http://schemas.openxmlformats.org/drawingml/2006/table")],
    );
    ctx.xml.start("a:tbl", &[]);
    ctx.xml.start("a:tblPr", &[("firstRow", "1"), ("bandRow", "1")]);
    ctx.xml.start("a:tableStyleId", &[]);
    ctx.xml.text("{5C22544A-7EE6-4342-B048-85BDC9FD1C3A}");
    ctx.xml.end("a:tableStyleId");
    ctx.xml.end("a:tblPr");
    // Schema: gridCols must be wrapped in a:tblGrid (PowerPoint strips the
    // whole table otherwise — its "repair" dialog is the symptom).
    ctx.xml.start("a:tblGrid", &[]);
    for w in &col_w {
        ctx.xml.empty("a:gridCol", &[("w", &w.to_string())]);
    }
    ctx.xml.end("a:tblGrid");
    let row_h = 370_840i64;
    for row in rows {
        ctx.xml.start("a:tr", &[("h", &row_h.to_string())]);
        for c in 0..cols {
            let cell = row.cells.get(c);
            ctx.xml.start("a:tc", &[]);
            ctx.xml.start("a:txBody", &[]);
            ctx.xml.empty("a:bodyPr", &[]);
            ctx.xml.start("a:lstStyle", &[]);
            ctx.xml.end("a:lstStyle");
            let runs = cell.map(|cl| flatten(cl)).unwrap_or_default();
            if runs.is_empty() {
                ctx.xml.start("a:p", &[]);
                ctx.xml.empty("a:endParaRPr", &[("lang", "en-US")]);
                ctx.xml.end("a:p");
            } else {
                let font = ctx.font.to_string();
                write_para(
                    ctx,
                    &[],
                    Some(PprChildren::NoBullet),
                    &runs,
                    ParaOpts {
                        size: Some(1400),
                        bold_all: row.is_header,
                        font: Some(font),
                        ..ParaOpts::default()
                    },
                );
            }
            ctx.xml.end("a:txBody");
            cell_props(ctx.xml, row.is_header);
            ctx.xml.end("a:tc");
        }
        ctx.xml.end("a:tr");
    }
    ctx.xml.end("a:tbl");
    ctx.xml.end("a:graphicData");
    ctx.xml.end("a:graphic");
    ctx.xml.end("p:graphicFrame");
}

fn cell_props(xml: &mut Xml, header: bool) {
    xml.start("a:tcPr", &[]);
    for side in ["a:lnL", "a:lnR", "a:lnT", "a:lnB"] {
        xml.start(side, &[("w", "9525")]);
        xml.start("a:solidFill", &[]);
        xml.empty("a:srgbClr", &[("val", "BFBFBF")]);
        xml.end("a:solidFill");
        xml.end(side);
    }
    if header {
        xml.start("a:solidFill", &[]);
        xml.empty("a:srgbClr", &[("val", "D9E2F3")]);
        xml.end("a:solidFill");
    }
    xml.end("a:tcPr");
}

/// Centered picture fitted into `geom`, preserving aspect ratio.
fn picture(
    ctx: &mut Ctx,
    geom: Geom,
    block_id: &str,
    alt: &str,
    assets: &AssetMap,
    media: &mut MediaAlloc,
) -> Result<(), Error> {
    let Some(asset) = assets.get(block_id).filter(|a| a.format == AssetFormat::Png) else {
        textbox(
            ctx,
            geom,
            &[PRun::text(&format!("[{alt} could not be rendered]"))],
            Some(1600),
            "A02020",
            false,
            false,
        );
        return Ok(());
    };
    let name = media.add_png(&asset.bytes);
    let rid = ctx.image_rid(&name);

    // Fit into at most 80% of the content area's width, full height.
    let max_w = geom.2 * 8 / 10;
    let max_h = geom.3;
    let (w, h) = match png_dimensions(&asset.bytes) {
        Some((pw, ph)) if pw > 0 && ph > 0 => {
            let scale = (max_w as f64 / pw as f64).min(max_h as f64 / ph as f64);
            ((pw as f64 * scale) as i64, (ph as f64 * scale) as i64)
        }
        _ => (max_w, max_h / 2),
    };
    let x = geom.0 + (geom.2 - w) / 2;
    let y = geom.1 + (geom.3 - h) / 2;

    let id = ctx.id();
    ctx.xml.start("p:pic", &[]);
    ctx.xml.start("p:nvPicPr", &[]);
    ctx.xml.empty(
        "p:cNvPr",
        &[
            ("id", &id.to_string()),
            ("name", &format!("Diagram {id}")),
            ("descr", &crate::docx::xml::esc_attr(alt)),
        ],
    );
    ctx.xml.start("p:cNvPicPr", &[]);
    ctx.xml.empty("a:picLocks", &[("noChangeAspect", "1")]);
    ctx.xml.end("p:cNvPicPr");
    ctx.xml.empty("p:nvPr", &[]);
    ctx.xml.end("p:nvPicPr");
    ctx.xml.start("p:blipFill", &[]);
    ctx.xml.empty("a:blip", &[("r:embed", &format!("rId{rid}"))]);
    ctx.xml.start("a:stretch", &[]);
    ctx.xml.empty("a:fillRect", &[]);
    ctx.xml.end("a:stretch");
    ctx.xml.end("p:blipFill");
    ctx.xml.start("p:spPr", &[]);
    xfrm_attrs(ctx.xml, (x, y, w, h));
    rect_geom(ctx.xml);
    ctx.xml.end("p:spPr");
    ctx.xml.end("p:pic");
    Ok(())
}

/// Code block: rounded gray box sized to its content, vertically centered
/// in `geom`, with an optional language caption.
fn code_box(ctx: &mut Ctx, geom: Geom, language: Option<&str>, code: &str) {
    let id = ctx.id();
    let inset_x = 228_600;
    // 12pt lines ~240k EMU each plus padding, clamped to the area.
    let line_count = code.lines().count() + usize::from(language.is_some());
    let height = (line_count as i64 * 240_000 + 320_000).min(geom.3);
    let geom = (
        geom.0 + inset_x,
        geom.1 + (geom.3 - height) / 2,
        geom.2 - 2 * inset_x,
        height,
    );
    ctx.xml.start("p:sp", &[]);
    ctx.xml.start("p:nvSpPr", &[]);
    ctx.xml.empty(
        "p:cNvPr",
        &[("id", &id.to_string()), ("name", &format!("Code {id}"))],
    );
    ctx.xml.empty("p:cNvSpPr", &[("txBox", "1")]);
    ctx.xml.empty("p:nvPr", &[]);
    ctx.xml.end("p:nvSpPr");
    ctx.xml.start("p:spPr", &[]);
    xfrm_attrs(ctx.xml, geom);
    ctx.xml.start("a:prstGeom", &[("prst", "roundRect")]);
    ctx.xml.start("a:avLst", &[]);
    ctx.xml.end("a:avLst");
    ctx.xml.end("a:prstGeom");
    ctx.xml.start("a:solidFill", &[]);
    ctx.xml.empty("a:srgbClr", &[("val", "F5F5F5")]);
    ctx.xml.end("a:solidFill");
    ctx.xml.start("a:ln", &[("w", "9525")]);
    ctx.xml.start("a:solidFill", &[]);
    ctx.xml.empty("a:srgbClr", &[("val", "DDDDDD")]);
    ctx.xml.end("a:solidFill");
    ctx.xml.end("a:ln");
    ctx.xml.end("p:spPr");
    ctx.xml.start("p:txBody", &[]);
    ctx.xml.empty(
        "a:bodyPr",
        &[("wrap", "square"), ("lIns", "182880"), ("tIns", "91440")],
    );
    ctx.xml.start("a:lstStyle", &[]);
    ctx.xml.end("a:lstStyle");
    if let Some(lang) = language {
        write_para(
            ctx,
            &[("marL".into(), "0".into()), ("indent".into(), "0".into())],
            Some(PprChildren::NoBullet),
            &[PRun {
                bold: true,
                italic: true,
                strike: false,
                code: false,
                link: None,
                text: lang.to_string(),
            }],
            ParaOpts {
                size: Some(1100),
                color: Some("8A8A8A"),
                ..ParaOpts::default()
            },
        );
    }
    for line in code.lines() {
        if line.is_empty() {
            ctx.xml.start("a:p", &[]);
            ctx.xml
                .empty("a:endParaRPr", &[("lang", "en-US"), ("sz", "1200")]);
            ctx.xml.end("a:p");
        } else {
            write_para(
                ctx,
                &[("marL".into(), "0".into()), ("indent".into(), "0".into())],
                Some(PprChildren::NoBullet),
                &[PRun {
                    bold: false,
                    italic: false,
                    strike: false,
                    code: true,
                    link: None,
                    text: line.to_string(),
                }],
                ParaOpts {
                    size: Some(1200),
                    color: Some("24292E"),
                    ..ParaOpts::default()
                },
            );
        }
    }
    ctx.xml.end("p:txBody");
    ctx.xml.end("p:sp");
}
